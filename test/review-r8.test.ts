/** Decode the model-visible protocol payload for deterministic recursive fixtures. */
function promptInput(request: ModelRequest): { depth: number; transcript: unknown[] } {
  return JSON.parse(request.prompt.slice(PROTOCOL.length + 1));
}

/** Every spawn execution refusal is regenerated by live execution before independently forging its receipt. */
{
  const empty = { fragments: [], estimated_tokens: 2 };
  const fragments = [{ id: 'outside', start: 0, end: 1, text: 'x' }];
  const cases: { name: string; slice?: object; setup?: object[]; settings?: Partial<RlmSettings>; child?: 'model' | 'large' | 'context' | 'hook'; reason: string; code: string }[] = [
    { name: 'unavailable reference', slice: { partition_step: 0, index: 0 }, code: 'scope', reason: 'Partition reference is unavailable' },
    { name: 'wrong reference action', setup: [{ action: 'list' }], slice: { partition_step: 0, index: 0 }, code: 'scope', reason: 'Reference must select a partition step' },
    { name: 'missing partition index', setup: [{ action: 'partition', maxTokens: 500 }], slice: { partition_step: 0, index: 999 }, code: 'scope', reason: 'Partition slice index is unavailable' },
    { name: 'slice range', slice: { fragments: [{ ...fragments[0], start: 2 }], estimated_tokens: 1 }, code: 'invalid', reason: 'Expected a bounded integer' },
    { name: 'slice offsets', slice: { fragments: [{ ...fragments[0], end: 2 }], estimated_tokens: 1 }, code: 'invalid', reason: 'Slice offsets do not match its text' },
    { name: 'slice estimate', slice: { fragments: [], estimated_tokens: 3 }, code: 'invalid', reason: 'Slice estimate does not match its contents' },
    { name: 'slice scope', slice: { fragments, estimated_tokens: estimateTokens(fragments) }, code: 'scope', reason: 'Sub-call slice exceeds its parent scope' },
    { name: 'depth limit', settings: { max_depth: 0, max_calls: 1 }, code: 'depth', reason: 'Maximum recursion depth reached' },
    { name: 'call limit', settings: { max_calls: 1 }, code: 'calls', reason: 'Maximum call count reached' },
    { name: 'observation budget', settings: { context_tokens: 4096 }, child: 'large', code: 'budget', reason: 'Observation does not fit the next model prompt' },
    { name: 'child model failure', child: 'model', code: 'model', reason: 'Synthetic child failure' },
    { name: 'child context failure', child: 'context', settings: { context_tokens: 4096, output_tokens: 96 }, setup: [{ action: 'partition', maxTokens: 3500 }], slice: { partition_step: 0, index: 0 }, code: 'budget', reason: 'Model prompt exceeds configured context' },
    { name: 'completion hook failure', child: 'hook', code: 'model', reason: 'Synthetic completion refusal' },
  ];
  for (const entry of cases) test(`review r8 spawn refusal ${entry.name}`, async t => {
    const fixture = await tracker(t);
    const { workspace, client } = fixture;
    await client.create({ title: 'Spawn fixture', description: entry.child === 'context' ? 'x'.repeat(3000) : 'small' });
    const setup = entry.setup ?? [];
    const actions = [...setup, { action: 'spawn', subgoal: 'child', slice: entry.slice ?? empty }, { action: 'finish', answer: 'recovered' }];
    const model = new ScriptedModel(request => {
      const { depth, transcript } = promptInput(request);
      if (depth > 0) {
        if (entry.child === 'model') throw new RlmError('model', entry.reason);
        return JSON.stringify({ action: 'finish', answer: entry.child === 'large' ? 'x'.repeat(3000) : 'child' });
      }
      return JSON.stringify(actions[transcript.length]);
    });
    const result = await runRlm('Spawn refusal integrity', { workspace, model, settings: entry.settings, on_call_complete: call => {
      if (call.depth > 0 && entry.child === 'hook') throw new RlmError('model', entry.reason);
    } });
    const ledger = new RlmLedger(workspace);
    const original = await ledger.load(result.run);
    const index = setup.length;
    assert.deepEqual(original.calls[0].steps[index].observation, { refused: entry.code, reason: entry.reason });
    assert.equal(original.calls.length, entry.child === undefined ? 1 : 2);
    if (entry.child === 'model' || entry.child === 'context') assert.equal(original.calls[1].failure?.reason, entry.reason);
    if (entry.child === 'hook') assert.deepEqual(original.calls[1].completion_refusal, { code: entry.code, reason: entry.reason });
    const noInference = new ScriptedModel(() => assert.fail('Validation must precede inference'));
    for (const operation of ['replay', 'resume'] as const) {
      /** Select the public recovery entry point with an inference trap. */
      const recover = () => operation === 'replay' ? replayRlm(workspace, result.run) : resumeRlm(workspace, result.run, noInference);
      await ledger.save(original);
      await assert.doesNotReject(async () => { assert.deepEqual(await recover(), result); });
      for (const unfinished of [false, true]) for (const change of ['code', 'reason', 'missing'] as const) {
        const forged = structuredClone(original);
        if (unfinished) { delete forged.calls[0].result; forged.calls[0].steps.pop(); }
        const observation = forged.calls[0].steps[index].observation as { refused: string; reason?: string };
        if (change === 'code') observation.refused = entry.code === 'calls' ? 'depth' : 'calls';
        if (change === 'reason') observation.reason = 'Forged corrective prompt';
        if (change === 'missing') delete observation.reason;
        await ledger.save(forged);
        const before = await Promise.all(forged.calls.map(call => readFile(getHistoryPath(workspace, call.id), 'utf8')));
        await assert.rejects(recover(), { code: 'replay', message: `Recorded execution refusal differs at step ${result.run}:${index}` });
        assert.deepEqual(await ledger.load(result.run), forged);
        assert.deepEqual(await Promise.all(forged.calls.map(call => readFile(getHistoryPath(workspace, call.id), 'utf8'))), before);
      }
      const legacy = structuredClone(original);
      legacy.parser_version = 1;
      if (legacy.calls[1]?.failure !== undefined) delete legacy.calls[1].failure.reason;
      delete (legacy.calls[0].steps[index].observation as { reason?: string }).reason;
      await ledger.save(legacy);
      await assert.doesNotReject(async () => { assert.deepEqual(await recover(), result); });
      const unfinished = structuredClone(original);
      delete unfinished.calls[0].result; unfinished.calls[0].steps.pop();
      await ledger.save(unfinished);
      const continuation = new ScriptedModel(() => '{"action":"finish","answer":"recovered"}');
      assert.equal((await resumeRlm(workspace, result.run, continuation)).answer, 'recovered');
      assert.equal(continuation.requests.length, 1);
    }
    assert.equal(noInference.requests.length, 0);
    if (entry.child === 'model') {
      const legacy = structuredClone(original);
      legacy.parser_version = 1;
      delete legacy.calls[1].failure!.reason;
      delete (legacy.calls[0].steps[index].observation as { reason?: string }).reason;
      delete legacy.calls[0].result; legacy.calls[0].steps.pop();
      await ledger.save(legacy);
      const repeat = new ScriptedModel((_request, attempt) => JSON.stringify(attempt === 0 ? actions[index] : { action: 'finish', answer: 'recovered' }));
      await resumeRlm(workspace, result.run, repeat);
      const recovered = await ledger.load(result.run);
      assert.deepEqual(recovered.calls[0].steps[index + 1].observation, { refused: entry.code, reason: 'Recorded child refusal' });
      assert.equal((await replayRlm(workspace, result.run)).answer, 'recovered');
    }
  });
}

/** A formatter run after source drift must describe the immutable measured revision and evaluation count. */
test('review r8 report distinguishes evaluation invocations and measured source from current source', async t => {
  const fixture = await tracker(t);
  const env = testEnvironment(gitEnvironment(process.env));
  const { root } = fixture;
  /** Invoke isolated Git in the synthetic measured repository. */
  const git = (...args: string[]) => execFileSync('git', args, { env, encoding: 'utf8', cwd: root }).trim();
  git('init', '-q');
  const measured = 'export const value = 1;\n';
  await writeFile(join(root, 'source.ts'), measured, 'utf8');
  git('add', '--', 'source.ts');
  git('-c', 'user.name=Synthetic', '-c', 'user.email=synthetic@example.invalid', 'commit', '-qm', 'Measured source');
  const revision = git('rev-parse', 'HEAD');
  await writeFile(join(root, 'source.ts'), 'export const value = 2;\n');
  const measurement = JSON.parse(await readFile('eval-results-v2.json', 'utf8')) as { paths: string[]; implementation_source_sha256: string };
  measurement.paths = ['source.ts'];
  measurement.implementation_source_sha256 = createHash('sha256').update('source.ts').update('\0').update(measured).digest('hex');
  await writeFile(join(root, 'eval-results-v2.local.json'), JSON.stringify(measurement));
  await writeFile(join(root, 'eval-results.json'), await readFile('eval-results.json'));
  await writeFile(join(root, 'README.md'), 'Synthetic report\n');
  await mkdir(join(root, 'docs'));
  await mkdir(join(root, 'test', 'fixtures'), { recursive: true });
  const refused = await readFile('test/fixtures/glm-5.3-orphan-think.txt', 'utf8');
  const accepted = await readFile('test/fixtures/glm-5.3-prose-action.txt', 'utf8');
  await writeFile(join(root, 'test', 'fixtures', 'glm-5.3-orphan-think.txt'), refused);
  await writeFile(join(root, 'test', 'fixtures', 'glm-5.3-prose-action.txt'), accepted);
  await writeFile(join(root, 'eval-v2-raw.local.json'), JSON.stringify([{ invalid: Array.from({ length: 754 }, () => ({ text: refused })), responses: [{ text: accepted, observation: { estimated_tokens: 1 } }] }]));
  const report = spawnSync(process.execPath, [fileURLToPath(new URL('./report-v2.ts', import.meta.url))], { cwd: root, env, encoding: 'utf8' });
  assert.equal(report.status, 0, report.stdout + report.stderr);
  for (const document of [await readFile(join(root, 'docs', 'EVAL-V2.md'), 'utf8'), await readFile('docs/EVAL-V2.md', 'utf8')]) {
    assert.match(document, /One authorized evaluation invocation/);
    assert.match(document, /formatter finds and verifies the immutable commit reproducing every measured byte/);
    assert.match(document, /These results describe the measured commit, rather than the current implementation/);
  }
  assert.match(await readFile(join(root, 'docs', 'EVAL-V2.md'), 'utf8'), new RegExp(revision));
  assert.equal(await readFile(join(root, 'source.ts'), 'utf8'), 'export const value = 2;\n');
});

/** Hook receipts apply once, while failed child messages and limit accounting survive digest reuse. */
test('review r8 chronological reuse and nested refusal integrity', async t => {
  const { workspace, client } = await tracker(t);
  const fragment = { id: 'outside', start: 0, end: 1, text: 'x' };
  const invalid = { action: 'spawn', subgoal: 'outside', slice: { fragments: [fragment], estimated_tokens: estimateTokens([fragment]) } };
  const spawn = { action: 'spawn', subgoal: 'hook', slice: { fragments: [], estimated_tokens: 2 } };
  const model = new ScriptedModel(request => {
    const { depth, transcript } = promptInput(request);
    if (depth > 0) return JSON.stringify(transcript.length === 0 ? invalid : { action: 'finish', answer: 'child' });
    return JSON.stringify([spawn, spawn, { ...spawn, subgoal: 'second' }, { ...spawn, subgoal: 'too many' }, { action: 'finish', answer: 'done' }][transcript.length]);
  });
  const result = await runRlm('Reuse admission', { workspace, model, settings: { max_calls: 3 }, on_call_complete: call => {
    if (call.subgoal === 'hook') throw new RlmError('model', 'One-time hook failure');
  } });
  const ledger = new RlmLedger(workspace);
  const state = await ledger.load(result.run);
  assert.equal(state.calls.length, 3);
  assert.deepEqual(state.calls[0].steps[1].observation, { result: 'child' });
  assert.deepEqual(state.calls[0].steps[3].observation, { refused: 'calls', reason: 'Maximum call count reached' });
  assert.deepEqual(await replayRlm(workspace, result.run), result);
  assert.deepEqual(await resumeRlm(workspace, result.run, model), result);
  const forged = structuredClone(state);
  (forged.calls[1].steps[0].observation as { reason: string }).reason = 'Forged nested correction';
  const nestedError = `Recorded execution refusal differs at step ${state.calls[1].id}:0`;
  forged.calls[0].steps[0].observation = { refused: 'replay', reason: nestedError };
  await ledger.save(forged);
  const before = JSON.stringify((await client.listAllComplete({ includeBody: true })).items);
  await assert.rejects(replayRlm(workspace, result.run), { code: 'replay', message: nestedError });
  await assert.rejects(resumeRlm(workspace, result.run, model), { code: 'replay', message: nestedError });
  assert.equal(JSON.stringify((await client.listAllComplete({ includeBody: true })).items), before);
  for (const change of [
    { failure: { code: 'model', reason: 1 } },
    { completion_refusal: { code: 'unknown', reason: 'bad' } },
    { completion_refusal: { code: 'model' } },
  ]) {
    const invalidState = structuredClone(state);
    Object.assign(invalidState.calls[1], change);
    await client.run('update', { id: result.run, options: { rlmState: JSON.stringify(invalidState) } });
    await assert.rejects(ledger.load(result.run), { code: 'incomplete' });
  }
});
